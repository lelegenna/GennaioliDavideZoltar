    // Chiamato dal thread di ricezione: aggiorna la GUI nel thread giusto
    private void mostraRisposta(String risposta) {
        javax.swing.SwingUtilities.invokeLater(() -> {
            txtRisposta.setText(risposta);
            btnInvia.setEnabled(true);
        });
    }

    private void btnInviaActionPerformed(java.awt.event.ActionEvent evt) {
        String domanda = txtDomanda.getText().replace("\n", " ").trim();
        if (domanda.isEmpty()) {
            
            return;
        }
        String comando = cmbPersonalita.getSelectedItem() + ";" + domanda;
        btnInvia.setEnabled(false);
        client.invia(comando);
    }

